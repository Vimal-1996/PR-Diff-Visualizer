#!/usr/bin/env bash
# post_comment.sh — post a Markdown file as a pull request comment, updating
# the comment from an earlier run instead of adding a new one.
#
# Usage: post_comment.sh <body.md>
#
# Reads (environment):
#   GH_TOKEN   token with pull-requests: write
#   REPO       owner/name
#   PR_NUMBER  pull request number
#   HEAD_SHA   optional; shown in the comment footer
#
# The comment starts with a hidden marker, which is how later runs find it.

set -euo pipefail

MARKER='<!-- pr-diff-visualizer -->'
MAX_BYTES=64000   # GitHub rejects comment bodies over 65,536 characters

[[ $# -eq 1 && -f $1 ]] || { echo "usage: post_comment.sh <body.md>" >&2; exit 2; }
: "${REPO:?}" "${PR_NUMBER:?}"
[[ $PR_NUMBER =~ ^[0-9]+$ ]] || { echo "PR_NUMBER must be a number" >&2; exit 2; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

footer="<sub>Generated by pr-diff-visualizer"
[[ -n ${HEAD_SHA:-} ]] && footer+=" for commit ${HEAD_SHA:0:7}"
footer+=". Updated on every push.</sub>"

assemble() {  # assemble <content-file> > body
  printf '%s\n' "$MARKER"
  cat "$1"
  printf '\n\n---\n%s\n' "$footer"
}

assemble "$1" > "$tmp/body.md"

if [[ $(wc -c < "$tmp/body.md") -gt $MAX_BYTES ]]; then
  # First drop the collapsed raw diff stat, the least useful part.
  awk '
    /^<details>[[:space:]]*$/ { held = $0; hold = 1; next }
    hold { hold = 0; if ($0 ~ /Raw diff stat/) { skipping = 1; next } else print held }
    skipping { if ($0 ~ /^<\/details>/) skipping = 0; next }
    { print }
    END { if (hold) print held }
  ' "$1" > "$tmp/content.md"
  assemble "$tmp/content.md" > "$tmp/body.md"
  echo "Comment was too long; dropped the raw diff stat."
fi

if [[ $(wc -c < "$tmp/body.md") -gt $MAX_BYTES ]]; then
  head -c $((MAX_BYTES - 2000)) "$tmp/content.md" > "$tmp/cut.md"
  printf '\n\n_…cut short: the full result is over the size limit for a comment._\n' >> "$tmp/cut.md"
  assemble "$tmp/cut.md" > "$tmp/body.md"
  echo "Comment was still too long; cut it short."
fi

existing=$(gh api "repos/$REPO/issues/$PR_NUMBER/comments" --paginate \
  --jq ".[] | select(.body | startswith(\"$MARKER\")) | .id" | head -n 1)

if [[ -n $existing ]]; then
  gh api --method PATCH "repos/$REPO/issues/comments/$existing" -F "body=@$tmp/body.md" --jq '.html_url'
  echo "Updated the existing comment."
else
  gh api --method POST "repos/$REPO/issues/$PR_NUMBER/comments" -F "body=@$tmp/body.md" --jq '.html_url'
  echo "Created a new comment."
fi
